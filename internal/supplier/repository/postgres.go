// Package repository implements the persistence layer of the Supplier
// module on top of the shared Postgres pool. Every query filters on
// garage_id explicitly on top of the Row-Level Security policy and skips
// soft-deleted rows. See: Database Design Section 3.3.
package repository

import (
	"context"
	"encoding/json"
	"errors"
	"strings"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"

	platformdb "github.com/viettechno/vietgara-backend/internal/platform/db"
	"github.com/viettechno/vietgara-backend/internal/supplier/domain"
	"github.com/viettechno/vietgara-backend/internal/supplier/usecase"
	"github.com/viettechno/vietgara-backend/pkg/phone"
)

const pgUniqueViolation = "23505"

const (
	supplierColumns = `s.id, s.garage_id, s.name, s.tax_code, s.contact_info, s.bank_details, s.note, s.is_active,
		s.created_by, s.updated_by, s.created_at, s.updated_at`

	// supplierSearch filters live suppliers of garage $1. $2 is an ILIKE
	// pattern over name, tax code, contact person and email, $3 the digits
	// to look for in the phone (stored as E.164, see pkg/phone); "" disables
	// either. $4 also lists deactivated suppliers.
	supplierSearch = ` FROM suppliers s
		WHERE s.garage_id = $1 AND s.deleted_at IS NULL AND ($4::bool OR s.is_active)
		AND ($2::text = '' OR s.name ILIKE $2 OR s.tax_code ILIKE $2
			OR s.contact_info->>'contact_person' ILIKE $2 OR s.contact_info->>'email' ILIKE $2
			OR ($3::text <> '' AND s.contact_info->>'phone' LIKE $3))`
)

var likeEscaper = strings.NewReplacer(`\`, `\\`, `%`, `\%`, `_`, `\_`)

// containsPattern turns free text into an ILIKE "contains" pattern, or ""
// when there is nothing to match (the queries treat "" as "no filter").
func containsPattern(query string) string {
	if query == "" {
		return ""
	}

	return "%" + likeEscaper.Replace(query) + "%"
}

// phonePattern is containsPattern over the digits to look for inside stored
// E.164 numbers, so "0912 345" finds "+84912345678".
func phonePattern(query string) string {
	return containsPattern(phone.SearchKey(query))
}

// PostgresRepository implements usecase.Repository over the shared pgx
// pool.
type PostgresRepository struct {
	pool *platformdb.Pool
}

// NewPostgresRepository returns a supplier repository backed by pool.
func NewPostgresRepository(pool *platformdb.Pool) *PostgresRepository {
	return &PostgresRepository{pool: pool}
}

func scanSupplier(row pgx.Row) (*domain.Supplier, error) {
	var (
		s       domain.Supplier
		contact []byte
		bank    []byte
	)

	err := row.Scan(&s.ID, &s.GarageID, &s.Name, &s.TaxCode, &contact, &bank, &s.Note, &s.IsActive,
		&s.CreatedBy, &s.UpdatedBy, &s.CreatedAt, &s.UpdatedAt)
	if err != nil {
		return nil, err
	}

	if len(contact) > 0 {
		if err := json.Unmarshal(contact, &s.Contact); err != nil {
			return nil, err
		}
	}

	if len(bank) > 0 {
		if err := json.Unmarshal(bank, &s.Bank); err != nil {
			return nil, err
		}
	}

	return &s, nil
}

// translate maps a unique violation on the name index to
// domain.ErrSupplierNameTaken.
func translate(err error) error {
	var pgErr *pgconn.PgError

	if errors.As(err, &pgErr) && pgErr.Code == pgUniqueViolation &&
		pgErr.ConstraintName == "idx_suppliers_garage_name_unique" {
		return domain.ErrSupplierNameTaken
	}

	return err
}

// Create inserts s (whose id is generated by the caller) and scans back the
// server-generated timestamps.
func (r *PostgresRepository) Create(ctx context.Context, s *domain.Supplier) error {
	contact, err := json.Marshal(s.Contact)
	if err != nil {
		return err
	}

	bank, err := json.Marshal(s.Bank)
	if err != nil {
		return err
	}

	q := platformdb.QuerierFromContext(ctx, r.pool)
	row := q.QueryRow(ctx, `
		INSERT INTO suppliers (id, garage_id, name, tax_code, contact_info, bank_details, note, created_by, updated_by)
		VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)
		RETURNING created_at, updated_at`,
		s.ID, s.GarageID, s.Name, s.TaxCode, contact, bank, s.Note, s.CreatedBy, s.UpdatedBy,
	)

	return translate(row.Scan(&s.CreatedAt, &s.UpdatedAt))
}

// FindByID returns the live supplier, or domain.ErrSupplierNotFound.
func (r *PostgresRepository) FindByID(ctx context.Context, garageID, supplierID string) (*domain.Supplier, error) {
	if uuid.Validate(supplierID) != nil {
		return nil, domain.ErrSupplierNotFound
	}

	q := platformdb.QuerierFromContext(ctx, r.pool)

	s, err := scanSupplier(q.QueryRow(ctx,
		`SELECT `+supplierColumns+` FROM suppliers s WHERE s.garage_id = $1 AND s.id = $2 AND s.deleted_at IS NULL`,
		garageID, supplierID))
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, domain.ErrSupplierNotFound
	}

	return s, err
}

// Update persists the editable fields of s and scans back updated_at.
func (r *PostgresRepository) Update(ctx context.Context, s *domain.Supplier) error {
	contact, err := json.Marshal(s.Contact)
	if err != nil {
		return err
	}

	bank, err := json.Marshal(s.Bank)
	if err != nil {
		return err
	}

	q := platformdb.QuerierFromContext(ctx, r.pool)
	row := q.QueryRow(ctx, `
		UPDATE suppliers SET name = $3, tax_code = $4, contact_info = $5, bank_details = $6, note = $7, updated_by = $8
		WHERE garage_id = $1 AND id = $2 AND deleted_at IS NULL
		RETURNING updated_at`,
		s.GarageID, s.ID, s.Name, s.TaxCode, contact, bank, s.Note, s.UpdatedBy,
	)

	err = row.Scan(&s.UpdatedAt)
	if errors.Is(err, pgx.ErrNoRows) {
		return domain.ErrSupplierNotFound
	}

	return translate(err)
}

// List returns one page of live suppliers ordered by name.
func (r *PostgresRepository) List(ctx context.Context, garageID string, filter usecase.ListFilter) ([]*domain.Supplier, int, error) {
	q := platformdb.QuerierFromContext(ctx, r.pool)
	args := []any{garageID, containsPattern(filter.Query), phonePattern(filter.Query), filter.IncludeInactive}

	var total int
	if err := q.QueryRow(ctx, `SELECT count(*)`+supplierSearch, args...).Scan(&total); err != nil {
		return nil, 0, err
	}

	if total == 0 {
		return nil, 0, nil
	}

	rows, err := q.Query(ctx,
		`SELECT `+supplierColumns+supplierSearch+` ORDER BY lower(s.name), s.id LIMIT $5 OFFSET $6`,
		append(args, filter.Limit, filter.Offset)...)
	if err != nil {
		return nil, 0, err
	}
	defer rows.Close()

	items := make([]*domain.Supplier, 0, filter.Limit)

	for rows.Next() {
		item, err := scanSupplier(rows)
		if err != nil {
			return nil, 0, err
		}

		items = append(items, item)
	}

	return items, total, rows.Err()
}

// SoftDelete marks the supplier deleted, or returns
// domain.ErrSupplierNotFound.
func (r *PostgresRepository) SoftDelete(ctx context.Context, garageID, supplierID, deletedBy string) error {
	if uuid.Validate(supplierID) != nil {
		return domain.ErrSupplierNotFound
	}

	q := platformdb.QuerierFromContext(ctx, r.pool)

	var by *string
	if deletedBy != "" {
		by = &deletedBy
	}

	tag, err := q.Exec(ctx, `
		UPDATE suppliers SET deleted_at = now(), updated_by = $3
		WHERE garage_id = $1 AND id = $2 AND deleted_at IS NULL`,
		garageID, supplierID, by)
	if err != nil {
		return err
	}

	if tag.RowsAffected() == 0 {
		return domain.ErrSupplierNotFound
	}

	return nil
}

// SetActive deactivates or reactivates the supplier, or returns
// domain.ErrSupplierNotFound.
func (r *PostgresRepository) SetActive(ctx context.Context, garageID, supplierID string, active bool, updatedBy string) error {
	if uuid.Validate(supplierID) != nil {
		return domain.ErrSupplierNotFound
	}

	q := platformdb.QuerierFromContext(ctx, r.pool)

	var by *string
	if updatedBy != "" {
		by = &updatedBy
	}

	tag, err := q.Exec(ctx, `
		UPDATE suppliers SET is_active = $3, updated_by = $4
		WHERE garage_id = $1 AND id = $2 AND deleted_at IS NULL`,
		garageID, supplierID, active, by)
	if err != nil {
		return err
	}

	if tag.RowsAffected() == 0 {
		return domain.ErrSupplierNotFound
	}

	return nil
}
