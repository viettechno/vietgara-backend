package repository

import (
	"context"

	"github.com/jackc/pgx/v5"

	"github.com/viettechno/vietgara-backend/internal/customer/domain"
	platformdb "github.com/viettechno/vietgara-backend/internal/platform/db"
)

const linkColumns = `id, garage_id, customer_id, user_id, status::text, channel::text, requested_at, linked_at, ended_at`

var linkUniqueIndexes = map[string]error{
	"idx_customer_user_links_current": domain.ErrAlreadyLinked,
}

// PostgresLinkRepository implements usecase.LinkRepository over the shared
// pgx pool. Row-Level Security lets a garage's transaction see its own
// customers' links and a user's transaction see the links addressed to them.
type PostgresLinkRepository struct {
	pool *platformdb.Pool
}

// NewPostgresLinkRepository returns a link repository backed by pool.
func NewPostgresLinkRepository(pool *platformdb.Pool) *PostgresLinkRepository {
	return &PostgresLinkRepository{pool: pool}
}

func scanLink(row pgx.Row) (*domain.UserLink, error) {
	var (
		l       domain.UserLink
		status  string
		channel *string
	)

	err := row.Scan(&l.ID, &l.GarageID, &l.CustomerID, &l.UserID, &status, &channel, &l.RequestedAt, &l.LinkedAt, &l.EndedAt)
	if err != nil {
		return nil, err
	}

	l.Status = domain.LinkStatus(status)
	if channel != nil {
		l.Channel = domain.LinkChannel(*channel)
	}

	return &l, nil
}

// Create inserts l (whose id is generated by the caller) as a requested
// link, or as linked when it carries a channel. A customer that already has
// a current link returns domain.ErrAlreadyLinked.
func (r *PostgresLinkRepository) Create(ctx context.Context, l *domain.UserLink) error {
	q := platformdb.QuerierFromContext(ctx, r.pool)
	row := q.QueryRow(ctx, `
		INSERT INTO customer_user_links (id, garage_id, customer_id, user_id, status, channel, requested_at, linked_at)
		VALUES ($1, $2, $3, $4, $5::customer_user_link_status, $6::customer_user_link_channel, $7, $8)
		RETURNING requested_at`,
		l.ID, l.GarageID, l.CustomerID, l.UserID, string(l.Status), nullable(string(l.Channel)), l.RequestedAt, l.LinkedAt)

	return scanWrite(row, domain.ErrLinkNotFound, linkUniqueIndexes, nil, &l.RequestedAt)
}

// FindCurrent returns the customer's requested or linked link, or
// domain.ErrLinkNotFound.
func (r *PostgresLinkRepository) FindCurrent(ctx context.Context, garageID, customerID string) (*domain.UserLink, error) {
	if !isUUID(customerID) {
		return nil, domain.ErrLinkNotFound
	}

	return findOne(ctx, platformdb.QuerierFromContext(ctx, r.pool), domain.ErrLinkNotFound, scanLink,
		`SELECT `+linkColumns+` FROM customer_user_links
		WHERE garage_id = $1 AND customer_id = $2 AND status IN ('requested', 'linked')`,
		garageID, customerID)
}

// FindForUser returns one of the user's own links, or domain.ErrLinkNotFound.
func (r *PostgresLinkRepository) FindForUser(ctx context.Context, userID, linkID string) (*domain.UserLink, error) {
	if !isUUID(linkID) {
		return nil, domain.ErrLinkNotFound
	}

	return findOne(ctx, platformdb.QuerierFromContext(ctx, r.pool), domain.ErrLinkNotFound, scanLink,
		`SELECT `+linkColumns+` FROM customer_user_links WHERE user_id = $1 AND id = $2`, userID, linkID)
}

// ListOpenForUser returns the user's requested and linked links across
// garages, newest request first.
func (r *PostgresLinkRepository) ListOpenForUser(ctx context.Context, userID string) ([]*domain.UserLink, error) {
	rows, err := platformdb.QuerierFromContext(ctx, r.pool).Query(ctx, `
		SELECT `+linkColumns+` FROM customer_user_links
		WHERE user_id = $1 AND status IN ('requested', 'linked')
		ORDER BY requested_at DESC, id`, userID)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	var links []*domain.UserLink

	for rows.Next() {
		l, err := scanLink(rows)
		if err != nil {
			return nil, err
		}

		links = append(links, l)
	}

	return links, rows.Err()
}

// HasAny reports whether the customer was ever linked to, or asked of, the
// user, whatever the outcome.
func (r *PostgresLinkRepository) HasAny(ctx context.Context, customerID, userID string) (bool, error) {
	var exists bool

	err := platformdb.QuerierFromContext(ctx, r.pool).QueryRow(ctx, `
		SELECT EXISTS (SELECT 1 FROM customer_user_links WHERE customer_id = $1 AND user_id = $2)`,
		customerID, userID).Scan(&exists)

	return exists, err
}

// Update persists l's status, channel and timestamps.
func (r *PostgresLinkRepository) Update(ctx context.Context, l *domain.UserLink) error {
	q := platformdb.QuerierFromContext(ctx, r.pool)

	return execAffectingOne(ctx, q, domain.ErrLinkNotFound, `
		UPDATE customer_user_links
		SET status = $2::customer_user_link_status, channel = $3::customer_user_link_channel, linked_at = $4, ended_at = $5
		WHERE id = $1`,
		l.ID, string(l.Status), nullable(string(l.Channel)), l.LinkedAt, l.EndedAt)
}
