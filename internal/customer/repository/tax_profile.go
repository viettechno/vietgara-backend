package repository

import (
	"context"

	"github.com/jackc/pgx/v5"

	"github.com/viettechno/vietgara-backend/internal/customer/domain"
	platformdb "github.com/viettechno/vietgara-backend/internal/platform/db"
)

const taxProfileColumns = `id, garage_id, customer_id, kind::text, legal_name, tax_id, address, invoice_email, is_default, is_active,
	created_by, updated_by, created_at, updated_at`

var taxProfileUniqueIndexes = map[string]error{
	"idx_customer_tax_profiles_personal": domain.ErrPersonalProfileTaken,
}

// PostgresTaxProfileRepository implements usecase.TaxProfileRepository over
// the shared pgx pool.
type PostgresTaxProfileRepository struct {
	pool *platformdb.Pool
}

// NewPostgresTaxProfileRepository returns a tax profile repository backed
// by pool.
func NewPostgresTaxProfileRepository(pool *platformdb.Pool) *PostgresTaxProfileRepository {
	return &PostgresTaxProfileRepository{pool: pool}
}

func scanTaxProfile(row pgx.Row) (*domain.TaxProfile, error) {
	var (
		p    domain.TaxProfile
		kind string
	)

	err := row.Scan(&p.ID, &p.GarageID, &p.CustomerID, &kind, &p.LegalName, &p.TaxID, &p.Address, &p.InvoiceEmail,
		&p.IsDefault, &p.IsActive, &p.CreatedBy, &p.UpdatedBy, &p.CreatedAt, &p.UpdatedAt)
	if err != nil {
		return nil, err
	}

	p.Kind = domain.TaxProfileKind(kind)

	return &p, nil
}

// Create inserts p (whose id is generated by the caller) and scans back the
// server-generated timestamps.
func (r *PostgresTaxProfileRepository) Create(ctx context.Context, p *domain.TaxProfile) error {
	q := platformdb.QuerierFromContext(ctx, r.pool)
	row := q.QueryRow(ctx, `
		INSERT INTO customer_tax_profiles (id, garage_id, customer_id, kind, legal_name, tax_id, address, invoice_email,
			is_default, is_active, created_by, updated_by)
		VALUES ($1, $2, $3, $4::customer_tax_profile_kind, $5, $6, $7, $8, $9, $10, $11, $12)
		RETURNING created_at, updated_at`,
		p.ID, p.GarageID, p.CustomerID, string(p.Kind), p.LegalName, p.TaxID, p.Address, p.InvoiceEmail,
		p.IsDefault, p.IsActive, p.CreatedBy, p.UpdatedBy)

	return scanWrite(row, domain.ErrCustomerNotFound, taxProfileUniqueIndexes, domain.ErrCustomerNotFound, &p.CreatedAt, &p.UpdatedAt)
}

// FindByID returns the live profile of the customer, or
// domain.ErrTaxProfileNotFound.
func (r *PostgresTaxProfileRepository) FindByID(ctx context.Context, garageID, customerID, profileID string) (*domain.TaxProfile, error) {
	if !isUUID(profileID) || !isUUID(customerID) {
		return nil, domain.ErrTaxProfileNotFound
	}

	return findOne(ctx, platformdb.QuerierFromContext(ctx, r.pool), domain.ErrTaxProfileNotFound, scanTaxProfile,
		`SELECT `+taxProfileColumns+` FROM customer_tax_profiles
		WHERE garage_id = $1 AND customer_id = $2 AND id = $3 AND deleted_at IS NULL`,
		garageID, customerID, profileID)
}

// Update persists the editable fields of p and scans back updated_at.
func (r *PostgresTaxProfileRepository) Update(ctx context.Context, p *domain.TaxProfile) error {
	row := platformdb.QuerierFromContext(ctx, r.pool).QueryRow(ctx, `
		UPDATE customer_tax_profiles
		SET legal_name = $4, tax_id = $5, address = $6, invoice_email = $7, is_default = $8, updated_by = $9
		WHERE garage_id = $1 AND customer_id = $2 AND id = $3 AND deleted_at IS NULL
		RETURNING updated_at`,
		p.GarageID, p.CustomerID, p.ID, p.LegalName, p.TaxID, p.Address, p.InvoiceEmail, p.IsDefault, p.UpdatedBy)

	return scanWrite(row, domain.ErrTaxProfileNotFound, nil, nil, &p.UpdatedAt)
}

// List returns the customer's live profiles, the default first.
func (r *PostgresTaxProfileRepository) List(
	ctx context.Context, garageID, customerID string, includeInactive bool,
) ([]*domain.TaxProfile, error) {
	if !isUUID(customerID) {
		return nil, nil
	}

	rows, err := platformdb.QuerierFromContext(ctx, r.pool).Query(ctx, `
		SELECT `+taxProfileColumns+` FROM customer_tax_profiles
		WHERE garage_id = $1 AND customer_id = $2 AND deleted_at IS NULL AND ($3::bool OR is_active)
		ORDER BY is_default DESC, created_at, id`, garageID, customerID, includeInactive)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	var items []*domain.TaxProfile

	for rows.Next() {
		p, err := scanTaxProfile(rows)
		if err != nil {
			return nil, err
		}

		items = append(items, p)
	}

	return items, rows.Err()
}

// ClearDefault removes the default mark of the customer's profiles but
// exceptID's.
func (r *PostgresTaxProfileRepository) ClearDefault(ctx context.Context, garageID, customerID, exceptID string) error {
	_, err := platformdb.QuerierFromContext(ctx, r.pool).Exec(ctx, `
		UPDATE customer_tax_profiles SET is_default = FALSE
		WHERE garage_id = $1 AND customer_id = $2 AND id <> $3 AND is_default AND deleted_at IS NULL`,
		garageID, customerID, exceptID)

	return err
}

// SoftDelete marks the profile deleted, or returns
// domain.ErrTaxProfileNotFound.
func (r *PostgresTaxProfileRepository) SoftDelete(ctx context.Context, garageID, customerID, profileID, deletedBy string) error {
	if !isUUID(profileID) || !isUUID(customerID) {
		return domain.ErrTaxProfileNotFound
	}

	return execAffectingOne(ctx, platformdb.QuerierFromContext(ctx, r.pool), domain.ErrTaxProfileNotFound, `
		UPDATE customer_tax_profiles SET deleted_at = now(), is_default = FALSE, updated_by = $4
		WHERE garage_id = $1 AND customer_id = $2 AND id = $3 AND deleted_at IS NULL`,
		garageID, customerID, profileID, nullable(deletedBy))
}

// SetActive deactivates (clearing the default mark) or reactivates the
// profile, or returns domain.ErrTaxProfileNotFound.
func (r *PostgresTaxProfileRepository) SetActive(
	ctx context.Context, garageID, customerID, profileID string, active bool, updatedBy string,
) error {
	if !isUUID(profileID) || !isUUID(customerID) {
		return domain.ErrTaxProfileNotFound
	}

	return execAffectingOne(ctx, platformdb.QuerierFromContext(ctx, r.pool), domain.ErrTaxProfileNotFound, `
		UPDATE customer_tax_profiles SET is_active = $4, is_default = is_default AND $4, updated_by = $5
		WHERE garage_id = $1 AND customer_id = $2 AND id = $3 AND deleted_at IS NULL`,
		garageID, customerID, profileID, active, nullable(updatedBy))
}
