package repository

import (
	"context"
	"encoding/json"

	"github.com/jackc/pgx/v5"

	"github.com/viettechno/vietgara-backend/internal/customer/domain"
	"github.com/viettechno/vietgara-backend/internal/customer/usecase"
	platformdb "github.com/viettechno/vietgara-backend/internal/platform/db"
)

const (
	partnerColumns = `p.id, p.garage_id, p.type, p.name, p.tax_code, p.contact_info, p.note,
		p.created_by, p.updated_by, p.created_at, p.updated_at`

	// partnerSearch filters live partners of garage $1, optionally of type
	// $2 ("" = all). $3 is an ILIKE pattern over name, tax code, contact
	// person and email, $4 a compact pattern over the phone; "" disables
	// either.
	partnerSearch = ` FROM partners p
		WHERE p.garage_id = $1 AND p.deleted_at IS NULL
		AND ($2::text = '' OR p.type::text = $2)
		AND ($3::text = '' OR p.name ILIKE $3 OR p.tax_code ILIKE $3
			OR p.contact_info->>'contact_person' ILIKE $3 OR p.contact_info->>'email' ILIKE $3
			OR ($4::text <> '' AND p.contact_info->>'phone' LIKE $4))`
)

var partnerUniqueIndexes = map[string]error{
	"idx_partners_garage_type_name_unique": domain.ErrPartnerNameTaken,
}

// PostgresPartnerRepository implements usecase.PartnerRepository over the
// shared pgx pool.
type PostgresPartnerRepository struct {
	pool *platformdb.Pool
}

// NewPostgresPartnerRepository returns a partner repository backed by pool.
func NewPostgresPartnerRepository(pool *platformdb.Pool) *PostgresPartnerRepository {
	return &PostgresPartnerRepository{pool: pool}
}

func scanPartner(row pgx.Row) (*domain.Partner, error) {
	var (
		p           domain.Partner
		partnerType string
		contact     []byte
	)

	err := row.Scan(&p.ID, &p.GarageID, &partnerType, &p.Name, &p.TaxCode, &contact, &p.Note,
		&p.CreatedBy, &p.UpdatedBy, &p.CreatedAt, &p.UpdatedAt)
	if err != nil {
		return nil, err
	}

	p.Type = domain.PartnerType(partnerType)

	if len(contact) > 0 {
		if err := json.Unmarshal(contact, &p.Contact); err != nil {
			return nil, err
		}
	}

	return &p, nil
}

// Create inserts p (whose id is generated by the caller) and scans back the
// server-generated timestamps.
func (r *PostgresPartnerRepository) Create(ctx context.Context, p *domain.Partner) error {
	contact, err := json.Marshal(p.Contact)
	if err != nil {
		return err
	}

	q := platformdb.QuerierFromContext(ctx, r.pool)
	row := q.QueryRow(ctx, `
		INSERT INTO partners (id, garage_id, type, name, tax_code, contact_info, note, created_by, updated_by)
		VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)
		RETURNING created_at, updated_at`,
		p.ID, p.GarageID, string(p.Type), p.Name, p.TaxCode, contact, p.Note, p.CreatedBy, p.UpdatedBy,
	)

	return scanWrite(row, domain.ErrPartnerNotFound, partnerUniqueIndexes, nil, &p.CreatedAt, &p.UpdatedAt)
}

// FindByID returns the live partner, or domain.ErrPartnerNotFound.
func (r *PostgresPartnerRepository) FindByID(ctx context.Context, garageID, partnerID string) (*domain.Partner, error) {
	if !isUUID(partnerID) {
		return nil, domain.ErrPartnerNotFound
	}

	return findOne(ctx, platformdb.QuerierFromContext(ctx, r.pool), domain.ErrPartnerNotFound, scanPartner,
		`SELECT `+partnerColumns+` FROM partners p WHERE p.garage_id = $1 AND p.id = $2 AND p.deleted_at IS NULL`,
		garageID, partnerID)
}

// Update persists the editable fields of p and scans back updated_at.
func (r *PostgresPartnerRepository) Update(ctx context.Context, p *domain.Partner) error {
	contact, err := json.Marshal(p.Contact)
	if err != nil {
		return err
	}

	q := platformdb.QuerierFromContext(ctx, r.pool)
	row := q.QueryRow(ctx, `
		UPDATE partners SET type = $3, name = $4, tax_code = $5, contact_info = $6, note = $7, updated_by = $8
		WHERE garage_id = $1 AND id = $2 AND deleted_at IS NULL
		RETURNING updated_at`,
		p.GarageID, p.ID, string(p.Type), p.Name, p.TaxCode, contact, p.Note, p.UpdatedBy,
	)

	return scanWrite(row, domain.ErrPartnerNotFound, partnerUniqueIndexes, nil, &p.UpdatedAt)
}

// List returns one page of live partners ordered by name.
func (r *PostgresPartnerRepository) List(ctx context.Context, garageID string, filter usecase.PartnerFilter) ([]*domain.Partner, int, error) {
	args := []any{garageID, string(filter.Type), containsPattern(filter.Query), compactPattern(filter.Query)}

	return listPage(ctx, platformdb.QuerierFromContext(ctx, r.pool), scanPartner,
		`SELECT count(*)`+partnerSearch,
		`SELECT `+partnerColumns+partnerSearch+` ORDER BY lower(p.name), p.id LIMIT $5 OFFSET $6`,
		args, filter.Limit, filter.Offset)
}

// SoftDelete marks the partner deleted, or returns domain.ErrPartnerNotFound.
func (r *PostgresPartnerRepository) SoftDelete(ctx context.Context, garageID, partnerID, deletedBy string) error {
	if !isUUID(partnerID) {
		return domain.ErrPartnerNotFound
	}

	return execAffectingOne(ctx, platformdb.QuerierFromContext(ctx, r.pool), domain.ErrPartnerNotFound, `
		UPDATE partners SET deleted_at = now(), updated_by = $3
		WHERE garage_id = $1 AND id = $2 AND deleted_at IS NULL`,
		garageID, partnerID, nullable(deletedBy))
}
