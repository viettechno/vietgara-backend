package repository

import (
	"context"
	"encoding/json"

	"github.com/jackc/pgx/v5"

	"github.com/viettechno/vietgara-backend/internal/customer/domain"
	"github.com/viettechno/vietgara-backend/internal/customer/usecase"
	platformdb "github.com/viettechno/vietgara-backend/internal/platform/db"
)

const (
	customerColumns = `c.id, c.garage_id, c.full_name, c.phone, c.email, c.address, c.consent_log, c.is_active,
		c.created_by, c.updated_by, c.created_at, c.updated_at,
		(SELECT count(*) FROM vehicles v WHERE v.customer_id = c.id AND v.deleted_at IS NULL)::int,
		(SELECT l.status::text FROM customer_user_links l WHERE l.customer_id = c.id
			ORDER BY (l.status IN ('requested', 'linked')) DESC, l.created_at DESC LIMIT 1)`

	// customerSearch filters live customers of garage $1. $2 is an ILIKE
	// pattern over name/email, $3 a compact pattern over the plates of the
	// customer's vehicles and $4 the digits to look for in the phone (stored
	// as E.164, see pkg/phone); "" disables either filter. $5 also lists
	// deactivated customers.
	customerSearch = ` FROM customers c
		WHERE c.garage_id = $1 AND c.deleted_at IS NULL AND ($5::bool OR c.is_active)
		AND ($2::text = '' OR c.full_name ILIKE $2 OR c.email ILIKE $2
			OR ($4::text <> '' AND c.phone LIKE $4)
			OR ($3::text <> '' AND EXISTS (
				SELECT 1 FROM vehicles v
				WHERE v.customer_id = c.id AND v.deleted_at IS NULL AND v.license_plate_key LIKE $3)))`
)

var customerUniqueIndexes = map[string]error{
	"idx_customers_garage_phone_unique": domain.ErrPhoneTaken,
}

// PostgresCustomerRepository implements usecase.CustomerRepository over the
// shared pgx pool.
type PostgresCustomerRepository struct {
	pool *platformdb.Pool
}

// NewPostgresCustomerRepository returns a customer repository backed by pool.
func NewPostgresCustomerRepository(pool *platformdb.Pool) *PostgresCustomerRepository {
	return &PostgresCustomerRepository{pool: pool}
}

func scanCustomer(row pgx.Row) (*domain.Customer, error) {
	var (
		c          domain.Customer
		consent    []byte
		linkStatus *string
	)

	err := row.Scan(&c.ID, &c.GarageID, &c.FullName, &c.Phone, &c.Email, &c.Address, &consent, &c.IsActive,
		&c.CreatedBy, &c.UpdatedBy, &c.CreatedAt, &c.UpdatedAt, &c.VehicleCount, &linkStatus)
	if err != nil {
		return nil, err
	}

	if linkStatus != nil {
		c.LinkStatus = domain.LinkStatus(*linkStatus)
	}

	if len(consent) > 0 {
		if err := json.Unmarshal(consent, &c.ConsentLog); err != nil {
			return nil, err
		}
	}

	return &c, nil
}

func consentJSON(c *domain.Customer) ([]byte, error) {
	if c.ConsentLog == nil {
		return []byte("[]"), nil
	}

	return json.Marshal(c.ConsentLog)
}

// Create inserts c (whose id is generated by the caller) and scans back the
// server-generated timestamps.
func (r *PostgresCustomerRepository) Create(ctx context.Context, c *domain.Customer) error {
	consent, err := consentJSON(c)
	if err != nil {
		return err
	}

	q := platformdb.QuerierFromContext(ctx, r.pool)
	row := q.QueryRow(ctx, `
		INSERT INTO customers (id, garage_id, full_name, phone, email, address, consent_log, created_by, updated_by)
		VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)
		RETURNING created_at, updated_at`,
		c.ID, c.GarageID, c.FullName, c.Phone, c.Email, c.Address, consent, c.CreatedBy, c.UpdatedBy,
	)

	return scanWrite(row, domain.ErrCustomerNotFound, customerUniqueIndexes, nil, &c.CreatedAt, &c.UpdatedAt)
}

// FindByID returns the live customer, or domain.ErrCustomerNotFound.
func (r *PostgresCustomerRepository) FindByID(ctx context.Context, garageID, customerID string) (*domain.Customer, error) {
	if !isUUID(customerID) {
		return nil, domain.ErrCustomerNotFound
	}

	return findOne(ctx, platformdb.QuerierFromContext(ctx, r.pool), domain.ErrCustomerNotFound, scanCustomer,
		`SELECT `+customerColumns+` FROM customers c WHERE c.garage_id = $1 AND c.id = $2 AND c.deleted_at IS NULL`,
		garageID, customerID)
}

// CustomerRef identifies one garage's customer record.
type CustomerRef struct {
	ID       string
	GarageID string
}

// FindByEmailAcrossGarages returns every live customer record, in any
// garage, whose e-mail is email (case-insensitive) -- through the
// SECURITY DEFINER find_customers_by_email(), since the caller
// (the Customer App's signed-in person) belongs to none of those garages.
// It returns ids only: the records are then read in each garage's scope.
func (r *PostgresCustomerRepository) FindByEmailAcrossGarages(ctx context.Context, email string) ([]CustomerRef, error) {
	rows, err := platformdb.QuerierFromContext(ctx, r.pool).Query(ctx,
		`SELECT id, garage_id FROM find_customers_by_email($1) ORDER BY garage_id, id`, email)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	var refs []CustomerRef

	for rows.Next() {
		var ref CustomerRef
		if err := rows.Scan(&ref.ID, &ref.GarageID); err != nil {
			return nil, err
		}

		refs = append(refs, ref)
	}

	return refs, rows.Err()
}

// Update persists the editable fields of c and scans back updated_at.
func (r *PostgresCustomerRepository) Update(ctx context.Context, c *domain.Customer) error {
	consent, err := consentJSON(c)
	if err != nil {
		return err
	}

	q := platformdb.QuerierFromContext(ctx, r.pool)
	row := q.QueryRow(ctx, `
		UPDATE customers SET full_name = $3, phone = $4, email = $5, address = $6, consent_log = $7, updated_by = $8
		WHERE garage_id = $1 AND id = $2 AND deleted_at IS NULL
		RETURNING updated_at`,
		c.GarageID, c.ID, c.FullName, c.Phone, c.Email, c.Address, consent, c.UpdatedBy,
	)

	return scanWrite(row, domain.ErrCustomerNotFound, customerUniqueIndexes, nil, &c.UpdatedAt)
}

// List returns one page of live customers, newest first.
func (r *PostgresCustomerRepository) List(ctx context.Context, garageID string, filter usecase.ListFilter) ([]*domain.Customer, int, error) {
	args := []any{garageID, containsPattern(filter.Query), compactPattern(filter.Query), phonePattern(filter.Query), filter.IncludeInactive}

	return listPage(ctx, platformdb.QuerierFromContext(ctx, r.pool), scanCustomer,
		`SELECT count(*)`+customerSearch,
		`SELECT `+customerColumns+customerSearch+` ORDER BY c.created_at DESC, c.id LIMIT $6 OFFSET $7`,
		args, filter.Limit, filter.Offset)
}

// SoftDelete marks the customer deleted, or returns
// domain.ErrCustomerNotFound.
func (r *PostgresCustomerRepository) SoftDelete(ctx context.Context, garageID, customerID, deletedBy string) error {
	if !isUUID(customerID) {
		return domain.ErrCustomerNotFound
	}

	return execAffectingOne(ctx, platformdb.QuerierFromContext(ctx, r.pool), domain.ErrCustomerNotFound, `
		UPDATE customers SET deleted_at = now(), updated_by = $3
		WHERE garage_id = $1 AND id = $2 AND deleted_at IS NULL`,
		garageID, customerID, nullable(deletedBy))
}

// SetActive deactivates or reactivates the customer, or returns
// domain.ErrCustomerNotFound.
func (r *PostgresCustomerRepository) SetActive(ctx context.Context, garageID, customerID string, active bool, updatedBy string) error {
	if !isUUID(customerID) {
		return domain.ErrCustomerNotFound
	}

	return execAffectingOne(ctx, platformdb.QuerierFromContext(ctx, r.pool), domain.ErrCustomerNotFound, `
		UPDATE customers SET is_active = $3, updated_by = $4
		WHERE garage_id = $1 AND id = $2 AND deleted_at IS NULL`,
		garageID, customerID, active, nullable(updatedBy))
}
